/**
 * Слова, що описують готовність через КОЛІР. Людина з порушенням
 * кольоросприйняття не може на них покладатися, тому в рецептах вони
 * заборонені (перевіряється тестом tests/data.test.ts).
 * Дозволено: прозорість/непрозорість (яєчний білок), текстура, звук, запах,
 * час і температура всередині продукту.
 */
export const COLOR_CUE_PATTERNS: RegExp[] = [
  /золот/i, // золотистий
  /рум[’'ʼ]?ян/i, // рум'яний, підрум'янити
  /рожев/i, // рожевий
  /червон/i, // червоний, почервоніння
  /коричн/i, // коричневий
  /\bбур(ий|ого|ої|іти|іє)\b/i, // бурий, побуріє
  /потемн/i, // потемніння
  /змін\w* колір/i, // змінить колір
  /кольор/i, // колір/кольору (як ознака готовності)
  /сік\s+\S*\s*прозор|прозор\w*\s+сік/i, // «сік прозорий» — теж про колір
];

export function findColorCues(text: string): string[] {
  return COLOR_CUE_PATTERNS.filter((re) => re.test(text)).map((re) => re.source);
}
